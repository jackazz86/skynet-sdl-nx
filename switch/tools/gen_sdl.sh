#!/bin/sh
# Generates source/sdl_gen.c: dlsym table mapping the SDL_* names libSkyNet.so asks for
# (analysis/sdl_names.txt) onto the native Switch SDL3 (libSDL3.a). Names the native
# build does not export get no entry: dlsym logs them and returns NULL.
# Usage: tools/gen_sdl.sh <path to libSDL3.a>
cd "$(dirname "$0")/.." || exit 1
LIB=${1:-/c/work/nxsdl3/lib/libSDL3.a}
NM=${NM:-aarch64-none-elf-nm}
O=source/sdl_gen.c
$NM -g --defined-only "$LIB" 2>/dev/null | awk '$2=="T"||$2=="W"{print $3}' | grep '^SDL_' | sort -u > /tmp/sdl_have.txt
tr -d '\r' < analysis/sdl_names.txt | sort -u > /tmp/sdl_want.txt
comm -12 /tmp/sdl_want.txt /tmp/sdl_have.txt > /tmp/sdl_both.txt
cat tools/sdl_compat.txt >> /tmp/sdl_both.txt; sort -u /tmp/sdl_both.txt -o /tmp/sdl_both.txt
comm -23 /tmp/sdl_want.txt /tmp/sdl_both.txt > analysis/sdl_missing_native.txt
{
echo '/* GENERATED by tools/gen_sdl.sh -- do not edit. */'
echo '#include <stdint.h>'
echo '#include "so_util.h"'
tr -d '\r' < tools/sdl_override.txt | grep -v '^$' > /tmp/sdl_over.txt
while read -r n; do echo "extern void skynet_$n(void);"; done < /tmp/sdl_over.txt
grep -vxFf /tmp/sdl_over.txt /tmp/sdl_both.txt > /tmp/sdl_rest.txt
while read -r n; do echo "extern void $n(void);"; done < /tmp/sdl_rest.txt
echo 'DynLibFunction skynet_sdl_imports[] = {'
echo '  /* overrides first: dlsym returns the first match (see sdl_override.txt) */'
while read -r n; do echo "  { \"$n\", (uintptr_t)&skynet_$n },"; done < /tmp/sdl_over.txt
while read -r n; do echo "  { \"$n\", (uintptr_t)&$n },"; done < /tmp/sdl_rest.txt
echo '};'
echo 'const int skynet_sdl_imports_count = sizeof(skynet_sdl_imports)/sizeof(skynet_sdl_imports[0]);'
} > "$O"
echo "wanted $(wc -l < /tmp/sdl_want.txt), native $(wc -l < /tmp/sdl_both.txt), missing $(wc -l < analysis/sdl_missing_native.txt)"
