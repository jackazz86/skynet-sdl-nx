# Generates source/jni_gen.inc: ordered JNIEnv function names (JNI 1.6, 233 slots).
T = ["Object", "Boolean", "Byte", "Char", "Short", "Int", "Long", "Float", "Double", "Void"]
P = T[1:9]
n = ["", "", "", "",  # reserved
     "GetVersion", "DefineClass", "FindClass", "FromReflectedMethod", "FromReflectedField", "ToReflectedMethod",
     "GetSuperclass", "IsAssignableFrom", "ToReflectedField", "Throw", "ThrowNew", "ExceptionOccurred",
     "ExceptionDescribe", "ExceptionClear", "FatalError", "PushLocalFrame", "PopLocalFrame", "NewGlobalRef",
     "DeleteGlobalRef", "DeleteLocalRef", "IsSameObject", "NewLocalRef", "EnsureLocalCapacity", "AllocObject",
     "NewObject", "NewObjectV", "NewObjectA", "GetObjectClass", "IsInstanceOf", "GetMethodID"]
for t in T:
    n += [f"Call{t}Method", f"Call{t}MethodV", f"Call{t}MethodA"]
for t in T:
    n += [f"CallNonvirtual{t}Method", f"CallNonvirtual{t}MethodV", f"CallNonvirtual{t}MethodA"]
n += ["GetFieldID"] + [f"Get{t}Field" for t in T[:9]] + [f"Set{t}Field" for t in T[:9]]
n += ["GetStaticMethodID"]
for t in T:
    n += [f"CallStatic{t}Method", f"CallStatic{t}MethodV", f"CallStatic{t}MethodA"]
n += ["GetStaticFieldID"] + [f"GetStatic{t}Field" for t in T[:9]] + [f"SetStatic{t}Field" for t in T[:9]]
n += ["NewString", "GetStringLength", "GetStringChars", "ReleaseStringChars", "NewStringUTF", "GetStringUTFLength",
      "GetStringUTFChars", "ReleaseStringUTFChars", "GetArrayLength", "NewObjectArray", "GetObjectArrayElement",
      "SetObjectArrayElement"]
n += [f"New{t}Array" for t in P] + [f"Get{t}ArrayElements" for t in P] + [f"Release{t}ArrayElements" for t in P]
n += [f"Get{t}ArrayRegion" for t in P] + [f"Set{t}ArrayRegion" for t in P]
n += ["RegisterNatives", "UnregisterNatives", "MonitorEnter", "MonitorExit", "GetJavaVM", "GetStringRegion",
      "GetStringUTFRegion", "GetPrimitiveArrayCritical", "ReleasePrimitiveArrayCritical", "GetStringCritical",
      "ReleaseStringCritical", "NewWeakGlobalRef", "DeleteWeakGlobalRef", "ExceptionCheck", "NewDirectByteBuffer",
      "GetDirectBufferAddress", "GetDirectBufferCapacity", "GetObjectRefType"]
assert len(n) == 233, len(n)
out = ["/* GENERATED by tools/gen_jni.py */", "#define JNI_SLOTS 233",
       "static const char *const jni_names[JNI_SLOTS] = {"]
out += [f'  "{x}",' for x in n]
out += ["};"]
for i, x in enumerate(n):
    if x:
        out.append(f"static intptr_t jf_{i}(void) {{ return jni_unhandled({i}); }}")
out.append("static void *jni_table[JNI_SLOTS] = {")
out += [("  jf_%d," % i) if x else "  0," for i, x in enumerate(n)]
out.append("};")
open("source/jni_gen.inc", "w", newline="\n").write("\n".join(out) + "\n")
