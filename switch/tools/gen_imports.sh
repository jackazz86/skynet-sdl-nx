#!/bin/sh
# Generates source/imports_gen.c from analysis/undef_1.7.1.txt.
# Priority per symbol: shim_<name> defined in source/shim.c  >  tools/passthru.txt
# (ABI-identical in newlib)  >  logging stub returning 0.
cd "$(dirname "$0")/.." || exit 1
U=analysis/undef_1.7.1.txt; P=tools/passthru.txt; O=source/imports_gen.c; SHIM=source/shim.c
defined() { grep -Eq "^(SH\([^,]+, *$1,|FAIL\($1,)|[ )]FAIL\($1,|^(char|void) *shim_$1[\[ ;(]" "$SHIM"; }
{
echo '/* GENERATED by tools/gen_imports.sh -- do not edit. */'
echo '#include <stdint.h>'
echo '#include <stddef.h>'
echo '#include <math.h>'
echo '#include <stdlib.h>'
echo '#include <string.h>'
echo '#include <stdio.h>'
echo '#include <wchar.h>'
echo '#include <unistd.h>'
echo '#include <sys/stat.h>'
echo '#include <dirent.h>'
echo '#include <errno.h>'
echo '#include <zlib.h>'
echo 'int *__errno(void);'
echo '#include "so_util.h"'
echo '#include "imports.h"'
echo '#include "util.h"'
echo '#define STUB(n) static uintptr_t stub_##n(void) { static int once; if (!once++) debugPrintf("[stub] %s called\n", #n); return 0; }'
while read -r n; do
  n=$(echo "$n" | tr -d '\r'); [ -z "$n" ] && continue
  s=${n#__}
  if defined "$s"; then echo "extern char shim_$s[];"
  elif grep -qx "$n" "$P"; then :
  else echo "STUB($n)"; fi
done < "$U"
echo 'DynLibFunction skynet_libc_imports[] = {'
while read -r n; do
  n=$(echo "$n" | tr -d '\r'); [ -z "$n" ] && continue
  s=${n#__}
  if defined "$s"; then echo "  { \"$n\", (uintptr_t)&shim_$s },"
  elif grep -qx "$n" "$P"; then echo "  { \"$n\", (uintptr_t)&$n },"
  else echo "  { \"$n\", (uintptr_t)&stub_$n },"; fi
done < "$U"
echo '};'
echo 'const int skynet_libc_imports_count = sizeof(skynet_libc_imports)/sizeof(skynet_libc_imports[0]);'
} | tr -d '\r' > "$O"
