#!/bin/sh
# Generates source/imports_gen.c from analysis/undef_1.7.1.txt.
# Names in tools/passthru.txt (ABI-identical in newlib) map straight to the
# host function; every other name gets a logging stub that returns 0, so the
# first run lists exactly which shims the game really reaches.
cd "$(dirname "$0")/.." || exit 1
U=analysis/undef_1.7.1.txt; P=tools/passthru.txt; O=source/imports_gen.c
{
echo '/* GENERATED by tools/gen_imports.sh -- do not edit. */'
echo '#include <stdint.h>'
echo '#include <stddef.h>'
echo '#include "so_util.h"'
echo '#include "imports.h"'
echo '#include "util.h"'
echo '#include <math.h>'
echo '#include <stdlib.h>'
echo '#include <string.h>'
echo '#include <stdio.h>'
echo '#include <wchar.h>'
echo '#include <ctype.h>'
echo '#define STUB(n) static uintptr_t stub_##n(void) { static int once; if (!once++) debugPrintf("[stub] %s called\n", #n); return 0; }'
while read -r n; do
  [ -z "$n" ] && continue
  grep -qx "$n" "$P" || echo "STUB($n)"
done < "$U"
echo 'DynLibFunction skynet_libc_imports[] = {'
while read -r n; do
  [ -z "$n" ] && continue
  if grep -qx "$n" "$P"; then echo "  { \"$n\", (uintptr_t)&$n },"; else echo "  { \"$n\", (uintptr_t)&stub_$n },"; fi
done < "$U"
echo '};'
echo 'const int skynet_libc_imports_count = sizeof(skynet_libc_imports)/sizeof(skynet_libc_imports[0]);'
} | tr -d '\r' > "$O"
